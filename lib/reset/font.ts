export const ROWS = 7;
export const GAP = 1; // columns between glyphs

export function glyph(ch: string): string[] {
  return G[ch.toUpperCase()] ?? G[" "];
}

export function glyphWidth(ch: string): number {
  return glyph(ch)[0].length;
}

export type PlacedGlyph = { ch: string; x: number; w: number };

// Lay a single line out in dot columns. Returns glyph positions and total width.
export function layoutLine(text: string): { glyphs: PlacedGlyph[]; width: number } {
  const glyphs: PlacedGlyph[] = [];
  let x = 0;
  for (const ch of text) {
    const w = glyphWidth(ch);
    glyphs.push({ ch, x, w });
    x += w + GAP;
  }
  return { glyphs, width: Math.max(0, x - GAP) };
}

// Lit dot coordinates for one glyph, relative to its origin.
export function litDots(ch: string): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  glyph(ch).forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === "#") out.push([x, y]);
  });
  return out;
}

export function formatCount(n: number): string {
  return Math.max(0, Math.floor(n)).toLocaleString("en-US");
}
